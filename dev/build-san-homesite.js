#!/usr/bin/env node
/**
 * Builds public/homesite-san.html from public/homesite.html, and points the
 * SAN tracker's job links at it.
 *
 * Same approach as tracker-san-mpr.html: the page body is the live Homesite
 * Detail page unchanged, plus a fetch shim in <head> that sends its data calls
 * to the SAN endpoints. Re-run this after any fresh design export of
 * homesite.html so the SAN page stays in step with the live one.
 *
 * Every anchor must match an exact number of times or nothing is written.
 *
 *   node dev/build-san-homesite.js          # build
 *   node dev/build-san-homesite.js --check  # exit 1 if the output is stale
 */
'use strict';

const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const SRC = path.join(ROOT, 'public', 'homesite.html');
const OUT = path.join(ROOT, 'public', 'homesite-san.html');
const SAN_TRACKER = path.join(ROOT, 'public', 'tracker-san-mpr.html');

const SHIM = `<title>SAN Homesite Detail</title>
  <script>
    /* SAN Homesite Detail -- generated by dev/build-san-homesite.js from
       homesite.html. Do not hand-edit; re-run the script instead.
       Redirects this page's data calls to the SAN endpoints, the same way
       tracker-san-mpr.html does. Runs before the bundled page's own script.
       Jobs, saves and the change log all go to the SAN base. /api/walk-config
       is not rewritten: SAN has no walk roster of its own yet. */
    (function () {
      var ORIGINAL_FETCH = window.fetch.bind(window);
      var REWRITES = [
        ['/api/update-job-sandbox-san', null],
        ['/api/jobs-sandbox-san', null],
        ['/api/audit-san', null],
        ['/api/update-job', '/api/update-job-sandbox-san'],
        ['/api/jobs', '/api/jobs-sandbox-san'],
        ['/api/audit', '/api/audit-san']
      ];
      function rewrite(url) {
        var origin = window.location.origin;
        var abs = url.indexOf(origin) === 0;
        var p = abs ? url.slice(origin.length) : url;
        for (var i = 0; i < REWRITES.length; i++) {
          var from = REWRITES[i][0], to = REWRITES[i][1];
          if (p.indexOf(from) === 0) {
            var next = p.charAt(from.length);
            if (next && next !== '?' && next !== '/' && next !== '#') continue;
            if (to === null) return url;
            return (abs ? origin : '') + to + p.slice(from.length);
          }
        }
        return url;
      }
      window.fetch = function (input, init) {
        try {
          var isReq = typeof Request !== 'undefined' && input instanceof Request;
          var url = typeof input === 'string' ? input : (isReq ? input.url : String(input));
          var out = rewrite(url);
          if (out !== url) input = isReq ? new Request(out, input) : out;
        } catch (e) {
          console.warn('[san-homesite] fetch rewrite failed, using original URL', e);
        }
        return ORIGINAL_FETCH(input, init);
      };
    })();
  </script>`;

// [find, replace, expected count]
const HOMESITE_EDITS = [
  ['<title>Bundled Page</title>', SHIM, 1],
  ["'tracker.html'", "'tracker-san-mpr.html'", 2],
  ["can('tracker.edit')", "can('sandbox.edit')", 2],
  ["denyReason('tracker.edit')", "denyReason('sandbox.edit')", 2],
  ['>Homesite Detail<', '>SAN Homesite Detail<', 1],
  ["page: 'Homesite Detail'", "page: 'SAN Homesite Detail'", 1]
];

const TRACKER_EDITS = [
  ["'homesite.html') + '?job='", "'homesite-san.html') + '?job='", 1]
];

function apply(text, edits, label) {
  for (const [find, repl, want] of edits) {
    const got = text.split(find).length - 1;
    if (got !== want) {
      throw new Error(label + ': expected ' + want + ' of ' + JSON.stringify(find) + ', found ' + got);
    }
    text = text.split(find).join(repl);
  }
  return text;
}

const check = process.argv.includes('--check');
const built = apply(fs.readFileSync(SRC, 'utf8'), HOMESITE_EDITS, 'homesite.html');

if (check) {
  const cur = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
  if (cur !== built) {
    console.error('homesite-san.html is stale -- run node dev/build-san-homesite.js');
    process.exit(1);
  }
  console.log('homesite-san.html is current');
  process.exit(0);
}

fs.writeFileSync(OUT, built);
console.log('wrote public/homesite-san.html (' + built.length + ' bytes)');

// Tracker link: idempotent -- skip if already pointed at the SAN page.
let tracker = fs.readFileSync(SAN_TRACKER, 'utf8');
if (tracker.includes("'homesite-san.html') + '?job='")) {
  console.log('tracker-san-mpr.html already links to homesite-san.html');
} else {
  tracker = apply(tracker, TRACKER_EDITS, 'tracker-san-mpr.html');
  fs.writeFileSync(SAN_TRACKER, tracker);
  console.log('tracker-san-mpr.html job links now open homesite-san.html');
}
